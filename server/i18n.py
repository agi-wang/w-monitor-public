def language(accept_language):
    candidates = []
    for index, part in enumerate(accept_language[:2048].split(',')[:32]):
        pieces = part.strip().lower().split(';')
        code, quality = pieces[0], 1.0
        for parameter in pieces[1:]:
            match = re.fullmatch(r'\s*q\s*=\s*(0(?:\.\d{0,3})?|1(?:\.0{0,3})?)\s*', parameter)
            if not match:
                quality = 0
                break
            quality = float(match[1])
        if quality > 0 and (code == '*' or code == 'zh' or code.startswith('zh-') or code == 'en' or code.startswith('en-')):
            candidates.append((quality, -index, 'zh-CN' if code == 'zh' or code.startswith('zh-') else 'en'))
    return max(candidates)[2] if candidates else 'en'


def translate(message, locale):
    return EN.get(message, message) if locale == 'en' else message


def render_html(source, locale):
    if locale == 'en':
        for original in sorted(EN, key=len, reverse=True):
            source = source.replace(html.escape(original), html.escape(EN[original]))
    return source.replace('<html lang="zh-CN">', '<html lang="' + locale + '">')
